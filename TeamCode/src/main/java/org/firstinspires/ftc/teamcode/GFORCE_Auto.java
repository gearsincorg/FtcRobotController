@Autonomous(name = "G-FORCE AUTO", group = "Competition", preselectTeleOp = "G-FORCE TELEOP")
public class GFORCE_Auto extends CommandOpMode {
    // Top path speed in auto (inches/sec).  The production chassis can do about 94 forward.
    private static final double AUTO_MAX_SPEED = 20;
    private static final long SHOOT_TIMEOUT_MS = 4000;
    private boolean autoStarted = false;

    // Declare robot Subsystems
    private BiobuzzRobot robot = new BiobuzzRobot(this);

    private boolean appliedRed;

    @Override
    public void initialize() {
        super.reset();

        // Initialize Subsystems
        robot.initialize(AUTO_MAX_SPEED);

        // Home the turret at every auto init: it must be centered by hand (pointing straight
        // backwards).  Teleop keeps this count, so it doesn't home again.
        robot.shooter.homeTurret();

        // Volleys (robot.aimAndShootCommand) turn the chassis to the goal first; don't feed a ball
        // until it's there (ignored while ShooterSubsystem.TURRET_ENABLED: the turret aims, and the
        // chassis only turns if the turret is at a soft limit).
        robot.shooter.setRequireChassisAim(true);
    }

    /** Push the menu choices (goal side, start pose) to the robot whenever they change. */
    private void applyConfig() {
        robot.shooter.setAlliance(robot.config.red);
    }

    /** Run the setup menu and show the preload so the drive team can check both before START. */
    @Override
    public void initialize_loop() {
        robot.config.runMenu();
        applyConfig();

        robot.clearBulkCache();   // the scheduler doesn't run during init, so clear it here
        robot.intake.refreshSensors();

        telemetry.addData("Preload", "%d balls  [ %s]%s", robot.intake.ballCount(),
                robot.intake.slotPattern(), robot.intake.isSimulated() ? "  (SIMULATED)" : "");
        telemetry.addData("Turret", "homed at init: it must point straight back (re-init if not)");
        telemetry.update();
    }

    @Override
    public void run() {

        if (!autoStarted) {
            autoStarted = true;
            schedule(robot.config.routine.command(robot));   // runs from START
        }
        super.run();
        robot.update();
        showTelemetry();
    }

    public void showTelemetry() {
        if (robot.config.stepMode) {
            telemetry.addLine("STEP MODE: pauses after each path, press Cross to continue");
        }
        Pose pose = robot.drive.pose();
        telemetry.addData("Pose", "x %5.1f  y %5.1f  hdg %5.1f",
                pose.x(), pose.y(), Math.toDegrees(pose.heading()));
        // Follower : FOLLOWING busy  NearCenter_2 > point2 (2/2)
        telemetry.addData("Follower", "%s%s  %s", robot.drive.mode(),
                robot.drive.isBusy() ? " busy" : "", robot.pathStatus());
        telemetry.update();
    }
}
